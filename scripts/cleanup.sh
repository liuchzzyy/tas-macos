#!/usr/bin/env bash
# TAS cleanup: regenerable build products, superseded release artifacts and
# leftover in-app update backups.
#
#   scripts/cleanup.sh            dry run (prints what it would do)
#   scripts/cleanup.sh --apply     perform it; files move to the Trash
#   scripts/cleanup.sh --apply --build   also drop the SwiftPM build cache
#   scripts/cleanup.sh --apply --dist    also supersede old dist/*.dmg
#
# Never touched: vault data (~/.tas), database migration backups
# (index-before-versions-*.db), and the newest .TAS-backup-*.app, which is the
# only rollback copy of the installed app.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APPLY=0
BUILD=0
DIST=0

usage() { sed -n '2,13p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }
for arg in "$@"; do
  case "$arg" in
    --apply) APPLY=1 ;;
    --build) BUILD=1 ;;
    --dist) DIST=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $arg" >&2; usage; exit 2 ;;
  esac
done

trash() { # recoverable: move into the Trash, never unlink
  local path="$1" dest="$HOME/.Trash/$(basename "$1")"
  [ -e "$path" ] || return 0
  if [ "$APPLY" = 1 ]; then
    [ -e "$dest" ] && dest="$dest.$(date +%s)"
    mv "$path" "$dest"
    echo "  trashed $path"
  else
    echo "  would trash $path"
  fi
}

echo "repo: $ROOT"
echo "mode: $([ "$APPLY" = 1 ] && echo apply || echo dry-run)"

echo "[1/4] SwiftPM build cache"
if [ "$BUILD" = 1 ]; then
  for cache in .build .swiftpm; do
    if [ -d "$ROOT/$cache" ]; then
      echo "  removing $cache ($(du -sh "$ROOT/$cache" | cut -f1), regenerated by swift build)"
      [ "$APPLY" = 1 ] && rm -rf "${ROOT:?}/$cache"
    fi
  done
else
  echo "  skipped (pass --build; swift rebuilds it on demand)"
fi

echo "[2/4] git worktrees outside the main checkout"
git -C "$ROOT" worktree prune
while IFS= read -r path; do
  [ "$path" = "$ROOT" ] && continue
  [ -d "$path" ] || continue
  if [ -n "$(git -C "$path" status --porcelain)" ]; then
    echo "  keeping $path (uncommitted changes)"
  elif [ "$APPLY" = 1 ]; then
    git -C "$ROOT" worktree remove "$path" && echo "  removed $path"
  else
    echo "  would remove $path"
  fi
done < <(git -C "$ROOT" worktree list --porcelain | awk '/^worktree /{print $2}')

echo "[3/4] superseded in-app update backups next to the installed app"
for dir in /Applications; do
  # Newest backup stays: it is the only recovery copy of the previous version.
  while IFS= read -r backup; do
    trash "$backup"
  done < <(ls -1t "$dir"/.TAS-backup-*.app 2>/dev/null | tail -n +2 || true)
  for stray in "$dir"/.TAS-staging-*.app "$dir"/.TAS-failed-*.app; do
    [ -e "$stray" ] && trash "$stray"
  done
done

echo "[4/4] superseded release artifacts in dist/"
current="$(/usr/libexec/PlistBuddy -c 'Print CFBundleShortVersionString' "$ROOT/Resources/Info.plist" 2>/dev/null || echo '')"
for dmg in "$ROOT"/dist/TAS-*.dmg; do
  [ -e "$dmg" ] || continue
  case "$(basename "$dmg")" in
    *"-$current-"*) echo "  keeping $(basename "$dmg") (current version $current)" ;;
    *)
      if [ "$DIST" = 1 ]; then trash "$dmg"; else echo "  would trash $(basename "$dmg") (superseded by $current; pass --dist)"; fi
      ;;
  esac
done

echo "done. Trashed files stay recoverable until you empty the Trash."
